//! # nh-proto — the wire contracts
//!
//! The generated gRPC bindings for the NetworkHub API (ADR-0013). The `.proto`
//! sources in `proto/networkhub/v1` are the single source of truth; this crate
//! is what the Rust side (daemon, CLI, gateway) builds against, generated at
//! compile time by `build.rs`.
//!
//! Everything under [`v1`] is machine-generated. The [`descriptor`] module
//! exposes the compiled file descriptor set so the authorization interceptor
//! and tests can read each RPC's `required_permission` option (§10.3).

/// The generated `networkhub.v1` types and service stubs.
///
/// Generated by prost/tonic; the lint allowances below apply only to this
/// machine-generated code, not to hand-written code elsewhere in the crate.
pub mod v1 {
    #![allow(
        clippy::pedantic,
        clippy::all,
        missing_docs,
        missing_debug_implementations,
        unreachable_pub,
        // prost/tonic emit fully-qualified paths (std::result::Result, etc.);
        // the workspace warns on that for hand-written code, but it is correct
        // and unavoidable in generated code.
        unused_qualifications
    )]
    tonic::include_proto!("networkhub.v1");
}

/// The compiled file descriptor set for the API.
///
/// Used to read custom method options (notably `required_permission`) that are
/// not exposed as Rust constants by prost. The daemon's authorization
/// interceptor and the annotation-coverage test both read this.
pub mod descriptor {
    /// Raw bytes of the `FileDescriptorSet`, as emitted by `build.rs`.
    pub const FILE_DESCRIPTOR_SET: &[u8] =
        include_bytes!(concat!(env!("OUT_DIR"), "/networkhub_descriptor.bin"));
}

pub mod permissions;
